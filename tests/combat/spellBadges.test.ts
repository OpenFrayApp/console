/**
 * What every modelled spell puts on the row, in one readable table. The invariants
 * test proves the *shape* of each entry; this one pins the *wording*, so changing a
 * badge is a visible diff a reviewer can check against the spell text.
 *
 * Columns: key, targeting, the 2024 badge, and the 2014 badge when the editions
 * differ. `(Name)` means the effect carries no note, so the badge is the effect's own
 * name — how every condition is rendered.
 */

const spell = (name: string, edition: '5.0' | '5.5'): Spell => ({
  id: `test:${name}`,
  source: 'test',
  edition,
  name,
  level: 1,
  school: 'Abjuration',
  castingTime: 'action',
  range: 'touch',
  components: { verbal: true, somatic: true, material: false },
  duration: 'up to 1 minute',
  concentration: false,
  ritual: false,
  text: '',
})

/** Badges for one edition, joined with " + " when a spell applies two effects. */
const badges = (key: string, edition: '5.0' | '5.5'): string =>
  SPELL_EFFECTS[key]
    .build({ spell: spell(key, edition) })
    .map((e) => (e.note ? badgeLabel(e) : `(${e.name})`))
    .join(' + ')

