describe('spell badge wording', () => {
  it('has a row for every modelled spell', () => {
    expect(EXPECTED.map((r) => r[0]).sort()).toEqual(Object.keys(SPELL_EFFECTS).sort())
  })

  it.each(EXPECTED)('%s → %s', (key, targeting, badge, badge2014) => {
    expect(SPELL_EFFECTS[key].targeting).toBe(targeting)
    expect(badges(key, '5.5')).toBe(badge)
    expect(badges(key, '5.0')).toBe(badge2014 ?? badge)
  })
})
