import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const output = fileURLToPath(new URL('../src/types/database.ts', import.meta.url))

/** Generate the committed public-schema types from the fresh local database. */
function main() {
  const generated = execFileSync(
    'supabase',
    ['gen', 'types', 'typescript', '--local', '--schema', 'public'],
    { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] },
  )
  const header =
    '// SPDX-License-Identifier: AGPL-3.0-or-later\n' +
    '// Copyright (C) 2026 Nicola Mustone\n' +
    '// Generated by `npm run db:types`. Do not edit by hand.\n\n'
  writeFileSync(output, `${header}${generated.trimEnd()}\n`)
  console.log(`Generated database types: ${output}`)
}

main()
