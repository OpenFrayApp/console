-- **Only the two share capabilities are enforced today.** The `shares` policy asks may() at
-- publish time; nothing asks about create.*, so denying one changes nothing yet.
--
-- They are here anyway, and it is not decoration. A capability has to exist before a role can
-- be composed out of it, and the grants have to exist before anything checks them: the day an
-- RLS policy on `creatures` asks may('create.creature'), every account already holds it, and
-- the alternative is a migration that locks everybody out of their own library for as long as
-- it takes to notice. A campaign-editor role holding create.campaign and nothing else is then
-- rows in this table.

-- What each role may do, admin included. It used to be answered by a short-circuit in may()
-- and is answered from this table now, like everybody else. The three below are what no other
-- role reaches; the rest arrive by inheritance from moderator, editor and gm.
--
-- The cost of retiring that short-circuit is that a capability invented next year does not
-- reach an admin until a row here says so. Worth paying: it is visible in a table rather than
-- hidden in a function, and capabilities_of() shows exactly what somebody holds and why.
