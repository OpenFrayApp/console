-- Roles and capabilities for admin.openfray.app. The tracked migration order applies this
-- after the core console tables and before publishing and moderation authority.
--
-- Nothing in the console reads any of this. Every check happens inside a security
-- definer function that answers for auth.uid(), so the dashboard holds no
-- service-role key and a signed-in Game Master calling one by hand gets nothing.
--
-- ── Read this before adding a function here ─────────────────────────────────────
-- A security definer function runs as its owner and bypasses row-level security
-- completely. Three rules keep that from becoming a hole:
--
--   1. `set search_path = public` on every one. Without it, a caller who can create
--      objects in an earlier schema decides what `user_roles` means.
--   2. `revoke execute ... from public` on every one. PostgreSQL grants EXECUTE to
--      PUBLIC on a new function by default, and Supabase's `anon` inherits PUBLIC.
--      Granting to `authenticated` does not undo that; only the revoke does.
--   3. Touch only the tables named in the function's own comment. A definer function
--      that reads `encounters` or `shares` reads every account's rows at once.

-- ── Why not user_metadata ───────────────────────────────────────────────────────
-- The account default license lives in user_metadata, and the app validates it on
-- read because a user can write their own metadata with the anon key. A role written
-- there would be self-granted. Roles live in a table with no policies, and only the
-- functions below read it.

-- ── Roles ───────────────────────────────────────────────────────────────────────
-- One row per role held, so an account can hold several. `role` is text with a check
-- rather than an enum: adding a role is an insert here and a new constraint, never an
-- ALTER TYPE. `granted_by` records who did it, because a role change is the most
-- consequential write in this schema.

create table if not exists user_roles (
  owner_id uuid not null references auth.users on delete cascade,
  role text not null,
  note text,
  granted_by uuid references auth.users on delete set null,
  granted_at timestamptz not null default now(),
  primary key (owner_id, role),
  constraint role_known check (role in ('gm', 'admin', 'editor', 'moderator', 'creator'))
);
alter table user_roles enable row level security;
-- No policies at all, and the grants revoked explicitly. RLS with no policy already
-- denies; the revoke means a policy added by mistake later still finds no privilege.
revoke all on table user_roles from anon, authenticated;

-- ── Capabilities ────────────────────────────────────────────────────────────────
-- Every gate in the dashboard asks for a capability, never for a role. A new role is
-- then rows in the mapping and nothing else: no function is edited, and no screen
-- learns a fourth name. That is what makes "creator" cheap to define later.
--
-- The catalog exists so the set is knowable. A capability the catalog does not list is
-- false for everybody, admin included, so a typo at a call site denies instead of
-- granting. It also gives a grant screen something to enumerate.

create table if not exists capabilities (
  capability text primary key,
  description text not null
);
alter table capabilities enable row level security;
revoke all on table capabilities from anon, authenticated;

